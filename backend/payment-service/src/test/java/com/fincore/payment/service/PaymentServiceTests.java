package com.fincore.payment.service;

import com.fincore.payment.client.AccountServiceClient;
import com.fincore.payment.dto.PaymentRequest;
import com.fincore.payment.dto.PaymentResponse;
import com.fincore.payment.entity.Payment;
import com.fincore.payment.entity.PaymentStatus;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.web.client.HttpServerErrorException;
import org.springframework.web.server.ResponseStatusException;
import org.springframework.http.HttpStatus;
import tools.jackson.databind.JsonNode;

import java.math.BigDecimal;
import java.util.Optional;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.*;
import static org.mockito.Mockito.*;
import org.mockito.junit.jupiter.MockitoExtension;
@ExtendWith(MockitoExtension.class)
class PaymentServiceTests {

    @Mock
    private PaymentPersistenceService persistenceService;

    @Mock
    private AccountServiceClient accountServiceClient;

    @Mock
    private JsonNode result;

    @Mock
    private JsonNode statusNode;

    @Mock
    private JsonNode transactionIdNode;

    @Mock
    private JsonNode currencyNode;

    private PaymentService paymentService;

    private UUID ownerId;
    private UUID paymentId;
    private UUID sourceId;
    private UUID destinationId;

    private Payment payment;
    private PaymentRequest request;

    @BeforeEach
    void setUp() {
        paymentService = new PaymentService(
                persistenceService,
                accountServiceClient
        );

        ownerId = UUID.randomUUID();
        paymentId = UUID.randomUUID();
        sourceId = UUID.randomUUID();
        destinationId = UUID.randomUUID();

        request = new PaymentRequest(
                sourceId,
                destinationId,
                new BigDecimal("250.00"),
                "INR",
                "Test payment"
        );

        payment = new Payment();
        payment.setOwnerUserId(ownerId);
        payment.setSourceAccountId(sourceId);
        payment.setDestinationAccountId(destinationId);
        payment.setAmount(new BigDecimal("250.00"));
        payment.setCurrency("INR");
        payment.setDescription("Test payment");
        payment.setIdempotencyKey("test-key");
        payment.setStatus(PaymentStatus.PENDING);

        // The entity ID is generated by JPA in production.
        // For these unit tests, the persistence mock returns this payment.
    }

   @Test
void rejectsTransferToSameAccount() {
    PaymentRequest invalidRequest = new PaymentRequest(
            sourceId,
            sourceId,
            new BigDecimal("250.00"),
            "INR",
            "Invalid payment"
    );

    assertThrows(
            IllegalArgumentException.class,
            () -> paymentService.processPayment(
                    ownerId, invalidRequest, "token", "test-key"
            )
    );

    verifyNoInteractions(persistenceService, accountServiceClient);
}

    @Test
    void returnsExistingCompletedPaymentWithoutCallingAccountService() {
        payment.setStatus(PaymentStatus.COMPLETED);

        when(persistenceService.findByIdempotencyKey(ownerId, "test-key"))
                .thenReturn(Optional.of(payment));

        PaymentResponse response = paymentService.processPayment(
                ownerId, request, "token", "test-key"
        );

        assertEquals("COMPLETED", response.status());
        verifyNoInteractions(accountServiceClient);
        verify(persistenceService, never()).create(
                any(), any(), anyString()
        );
    }

    @Test
    void rejectsReusingIdempotencyKeyWithDifferentAmount() {
        when(persistenceService.findByIdempotencyKey(ownerId, "test-key"))
                .thenReturn(Optional.of(payment));

        PaymentRequest changedRequest = new PaymentRequest(
                sourceId,
                destinationId,
                new BigDecimal("999.00"),
                "INR",
                "Different payment"
        );

        assertThrows(
                IllegalArgumentException.class,
                () -> paymentService.processPayment(
                        ownerId, changedRequest, "token", "test-key"
                )
        );

        verifyNoInteractions(accountServiceClient);
    }

    @Test
    void keepsPaymentProcessingWhenAccountServiceReturnsServerError() {
        payment.setId(paymentId);

        when(persistenceService.findByIdempotencyKey(ownerId, "test-key"))
                .thenReturn(Optional.of(payment));

        when(persistenceService.markProcessing(paymentId))
                .thenAnswer(invocation -> {
                    payment.setStatus(PaymentStatus.PROCESSING);
                    return payment;
                });

        when(accountServiceClient.executeTransfer(
                any(), any(), any(), any(), any(), anyString()
        )).thenThrow(new HttpServerErrorException(
                HttpStatus.INTERNAL_SERVER_ERROR
        ));

        PaymentResponse response = paymentService.processPayment(
                ownerId, request, "token", "test-key"
        );

        assertEquals("PROCESSING", response.status());
        verify(persistenceService, never()).markFailed(
                any(), anyString()
        );
    }

    @Test
    void returnsOwnedPayment() {
        payment.setStatus(PaymentStatus.COMPLETED);

        when(persistenceService.findOwnedPayment(paymentId, ownerId))
                .thenReturn(Optional.of(payment));

        PaymentResponse response = paymentService.getPayment(
                paymentId, ownerId
        );

        assertEquals("COMPLETED", response.status());
    }

 @Test
void rejectsPaymentNotOwnedByUser() {
    when(persistenceService.findOwnedPayment(paymentId, ownerId))
            .thenReturn(Optional.empty());

    ResponseStatusException exception = assertThrows(
            ResponseStatusException.class,
            () -> paymentService.getPayment(paymentId, ownerId)
    );

    assertEquals(HttpStatus.NOT_FOUND, exception.getStatusCode());
}
}
